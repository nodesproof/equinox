# Solidity: subset (Foundry) — array literal besar mahal untuk kompilasi; ambil sampel.
def sol_val(val):
    return ("true" if val else "false") if isinstance(val, bool) else str(val)
def sol_rows(name, rows, fields, ret=None):
    # `fields` = (tipe, indeks kolom) dalam urutan DEKLARASI variabel v0..vN (stabil agar diff generator hanya bertambah);
    # `ret` = urutan indeks variabel pada return (default: urutan deklarasi).
    ret = list(range(len(fields))) if ret is None else ret
    lines = [f"    function {name}() internal pure returns ({', '.join(f'{fields[j][0]}[] memory' for j in ret)}) {{"]
    n = len(rows)
    for j, (ty, _) in enumerate(fields):
        lines.append(f"        {ty}[] memory v{j} = new {ty}[]({n});")
    for i_, r in enumerate(rows):
        for j, (ty, idx) in enumerate(fields):
            lines.append(f"        v{j}[{i_}] = {sol_val(r[idx])};")
    lines.append(f"        return ({', '.join(f'v{j}' for j in ret)});")
    lines.append("    }")
    return "\n".join(lines)
def sol_portfolio(name, cases):
    # Satu kasus per indeks `c`: array datar (k, t, isCall, oi) + skalar (s, r, sigma, capMult, sumMid, sumVega).
    lines = [f"    uint256 internal constant PORTFOLIO_CASES = {len(cases)};",
             f"    function {name}(uint256 c) internal pure returns (int256[] memory k, int256[] memory t, bool[] memory isCall, int256[] memory oi, int256 s, int256 r, int256 sigma, int256 capMult, int256 sumMid, int256 sumVega) {{"]
    for ci, (ks, ts, cs, ois, s, r, sg, cm, sm, sv) in enumerate(cases):
        n = len(ks)
        lines.append(f"        if (c == {ci}) {{")
        lines.append(f"            k = new int256[]({n}); t = new int256[]({n}); isCall = new bool[]({n}); oi = new int256[]({n});")
        for j in range(n):
            lines.append(f"            k[{j}] = {ks[j]}; t[{j}] = {ts[j]}; isCall[{j}] = {sol_val(cs[j])}; oi[{j}] = {ois[j]};")
        lines.append(f"            return (k, t, isCall, oi, {s}, {r}, {sg}, {cm}, {sm}, {sv});")
        lines.append("        }")
    lines.append(f'        revert("{name}: kasus tidak ada");')
    lines.append("    }")
    return "\n".join(lines)
