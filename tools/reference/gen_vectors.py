def rs_val(x):
    if isinstance(x, bool): return "true" if x else "false"
    if isinstance(x, float): return repr(x)
    if isinstance(x, (list, tuple)): return "&[" + ", ".join(rs_val(v) for v in x) + "]"
    return str(x)
def rs_tuple(t):
    return "(" + ", ".join(rs_val(x) for x in t) + ")"
def rs_arr(name, ty, rows):
    return f"pub const {name}: &[{ty}] = &[\n" + "".join(f"    {rs_tuple(r)},\n" for r in rows) + "];\n"
